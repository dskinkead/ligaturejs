import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(path.join(root, 'src/index.js'), 'utf8')
const api = readFileSync(path.join(root, 'docs/API.md'), 'utf8')
const required = [
  ['docs/QUICKSTART.md', /^# Ligature in five minutes$/m],
  ['docs/EXAMPLE-PORTAL.md', /^# Example portal$/m],
  ['docs/EXAMPLES.md', /^# Application recipes$/m],
  ['docs/REACT-COMPARISON.md', /^# Ligature and React$/m],
  ['docs/TROUBLESHOOTING.md', /^# Troubleshooting and FAQ$/m],
  ['docs/ARCHITECTURE.md', /^# Architecture and decisions$/m]
]
const missingDocs = required.filter(([file, heading]) => !heading.test(readFileSync(path.join(root, file), 'utf8')))
if (missingDocs.length) throw new Error(`Missing documentation contract: ${missingDocs.map(([file]) => file).join(', ')}`)

const exports = [...source.matchAll(/export\s*\{([^}]+)\}\s*from/gms)]
  .flatMap(match => match[1].split(',').map(entry => entry.trim().split(/\s+as\s+/)[0]).filter(Boolean))
  .sort()
const exportIndex = [
  '<!-- Generated by scripts/documentation-check.js; do not edit manually. -->',
  '# Public API export index', '',
  'This versioned index is generated from `src/index.js`. Behavioral guidance',
  'and examples live in [API.md](API.md).', '',
  ...exports.map(name => `- \`${name}\``), ''
].join('\n')
const indexPath = path.join(root, 'docs/API-EXPORTS.md')
if (process.argv.includes('--write')) writeFileSync(indexPath, exportIndex)
else if (readFileSync(indexPath, 'utf8') !== exportIndex) throw new Error('docs/API-EXPORTS.md is stale; run node scripts/documentation-check.js --write')
for (const name of ['defineComponent', 'createComponentRegistry', 'defineRoute', 'defineRepository', 'createStore', 'createForm', 'bundleStyles', 'createActionHandler']) {
  if (!api.includes(`\`${name}`)) throw new Error(`Canonical API is absent from docs/API.md: ${name}`)
}
console.log(`Documentation check passed (${exports.length} public exports, ${required.length} guides).`)
